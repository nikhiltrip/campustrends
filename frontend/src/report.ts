import { z } from "zod";
import type { Report } from "./types";

const count = z.number().int().nonnegative();
const fraction = z.number().min(0).max(1);
const timestamp = z
  .string()
  .refine((s) => Number.isFinite(Date.parse(s)), "Invalid timestamp");
const strings = z.array(z.string());
const metric = z.object({
  posts: count,
  positive_rate: fraction,
  precision_at_10: fraction,
  top_k: count,
  roc_auc: fraction.nullable(),
  average_precision: fraction,
  precision_at_half: fraction,
  recall_at_half: fraction,
  confusion_matrix: z.tuple([z.tuple([count, count]), z.tuple([count, count])]),
});
const topic = z.object({
  id: count.max(100),
  name: z.string(),
  keywords: strings.min(1),
  recent_count: count,
  previous_count: count,
  recent_share: fraction,
  previous_share: fraction,
  share_change: z.number().min(-1).max(1),
  status: z.string(),
  recent_high_count: count,
  examples: strings,
});
const schema = z.object({
  schema_version: z.literal(1),
  title: z.string(),
  provenance: z.string(),
  is_sample: z.boolean(),
  school: z.literal("UCLA"),
  data_start: timestamp,
  data_end: timestamp,
  calendar: z.array(
    z.object({ name: z.string(), start: timestamp, end: timestamp }),
  ),
  quality: z.record(z.string(), count),
  summary: z.object({
    total_posts: count,
    labeled_posts: count,
    high_posts: count,
    topic_count: count.min(1).max(100),
    platforms: strings,
  }),
  trends: z.object({
    window_days: count.min(1),
    end: timestamp,
    recent_start: timestamp,
    previous_start: timestamp,
    recent_total: count,
    previous_total: count,
    topics: z.array(topic).min(1),
  }),
  timeline: z.array(
    z.object({ date: timestamp, topic_id: count.max(100), count }),
  ),
  posts: z
    .array(
      z.object({
        id: z.string(),
        text: z.string(),
        upvotes: count,
        timestamp,
        platform: z.string(),
        topic_id: count.max(100),
        term: z.string(),
        week_of_term: count,
        high_engagement: z.boolean().nullable(),
        threshold: z.number().nullable(),
        split: z.string(),
        score: fraction.nullable(),
      }),
    )
    .min(1)
    .max(100000),
  archetypes: z.array(
    z.object({
      id: count,
      name: z.string(),
      keywords: strings,
      training_high_posts: count,
      examples: strings.min(1),
      recent_posts: count,
      recent_labeled_posts: count,
      recent_high_posts: count,
      recent_high_rate: fraction.nullable(),
    }),
  ),
  evaluation: z.object({
    selected_model: z.string(),
    selection_metric: z.string(),
    validation: z.record(z.string(), metric),
    test: metric,
    baseline: metric,
    splits: z
      .array(
        z.object({
          name: z.string(),
          count,
          start: timestamp,
          end: timestamp,
          positive_rate: fraction,
        }),
      )
      .length(3),
    embargo_days: count,
    feature_weights: z.array(
      z.object({ feature: z.string(), weight: z.number() }),
    ),
    limitations: strings,
  }),
});

export function validateReport(value: unknown): Report {
  const parsed = schema.safeParse(value);
  if (!parsed.success)
    throw Error(
      "Choose a valid CampusTrendsML report.json generated by the current pipeline.",
    );
  const report = parsed.data;
  const ids = new Set(report.trends.topics.map((t) => t.id));
  const validIds = report.trends.topics.every(
    (t) => t.id < report.summary.topic_count,
  );
  const validPosts = report.posts.every((p) => ids.has(p.topic_id));
  const validTimeline = report.timeline.every((p) => ids.has(p.topic_id));
  if (
    ids.size !== report.summary.topic_count ||
    !validIds ||
    !validPosts ||
    !validTimeline ||
    report.summary.total_posts !== report.posts.length ||
    Date.parse(report.data_start) > Date.parse(report.data_end)
  ) {
    throw Error(
      "This report contains inconsistent topics, dates, or post counts.",
    );
  }
  return report;
}
